from __future__ import annotations

from typing import Any


def _single(topic: str, stem: str, correct: str, wrongs: list[str], rationale: str, importance: int = 4, frequency: float = 2.4) -> dict[str, Any]:
    choices = [correct, *wrongs[:4]]
    return {
        'type': 'single',
        'topic': topic,
        'text': f'国試風強化: {stem}',
        'choices': choices,
        'correct': ['1'],
        'short': rationale,
        'standard': rationale,
        'detailed': rationale + ' 正答根拠と誤答選択肢の差を一つずつ説明できるようにしてください。',
        'importance': importance,
        'frequency': frequency,
        'choice_explanations': [
            rationale,
            *[f'{wrong}は関連語ですが、この設問では「{correct}」を選ぶ根拠から外れます。' for wrong in choices[1:]],
        ],
    }


def _tf(topic: str, stem: str, correct_is_true: bool, rationale: str, importance: int = 4, frequency: float = 2.2) -> dict[str, Any]:
    return {
        'type': 'truefalse',
        'topic': topic,
        'text': f'国試風強化: {stem}',
        'choices': ['正しい', '誤り'],
        'correct': ['1' if correct_is_true else '2'],
        'short': rationale,
        'standard': rationale,
        'detailed': rationale + ' 正誤を決める語句を確認してください。',
        'importance': importance,
        'frequency': frequency,
        'choice_explanations': [
            rationale if correct_is_true else '設問文は条件や因果関係に誤りがあります。',
            rationale if not correct_is_true else '設問文は正しい内容です。',
        ],
    }


def _num(topic: str, stem: str, answer: float, unit: str, rationale: str, tolerance: float = 0.01, importance: int = 4, frequency: float = 2.2) -> dict[str, Any]:
    return {
        'type': 'numeric',
        'topic': topic,
        'text': f'国試風強化: {stem}',
        'numeric_answer': answer,
        'unit': unit,
        'short': rationale,
        'standard': rationale,
        'detailed': rationale + ' 公式、単位、代入、桁の妥当性の順に確認してください。',
        'importance': importance,
        'frequency': frequency,
        'tolerance': tolerance,
    }


